#pragma once
// =============================================================================
// Data flash settings the phone app may change.
//
// Two layers, both with addresses from TRM SLUUBT5C table 19-1 (firmware
// 4800_0_04), and every write read back and compared:
//
//   - The generated catalog (df_catalog.h): every BQStudio Data Memory
//     parameter except the ones tools/gen_df_catalog.py marks read only,
//     within TI's own min/max. Written by address with dfWriteAddress.
//   - The curated list in df_settings.cpp: 42 settings with safe LiFePO4
//     ranges, bit masks, and for threshold/recovery pairs the order the two
//     must keep. These rules also apply when the same address is written
//     through dfWriteAddress.
//
// Ranges are for this pack's LiFePO4 cells. Before reusing the firmware with
// another chemistry, revisit kItems in df_settings.cpp.
//
// The HTTP dashboard cannot change settings: the Wi-Fi AP has no
// authentication. The only way in is the BLE CMD characteristic, which needs
// a passkey-paired link.
// =============================================================================
#include "BQ40Z80.h"
#include <cstddef>
#include <cstdint>

#define DF_SETTINGS_VERSION 1

enum class DfWriteResult : uint8_t {
    Ok,
    UnknownId,     // not in the list
    OutOfRange,    // outside the item's min/max
    Conflict,      // would cross its partner (e.g. recovery above threshold)
    Sealed,        // gauge is SEALED; data flash writes are ignored
    BusBusy,       // could not get the SMBus from the poll task
    WriteFailed,   // SMBus error on the write
    VerifyFailed,  // read back a different value
};

void dfSettingsInit(BQ40Z80 *gauge);

// Reads every listed setting from the gauge and packs it for the SETTINGS
// characteristic (layout in docs/BLE_PROTOCOL.md). Returns 0 on failure.
size_t dfSettingsBuildPacket(uint8_t *buf, size_t cap);

// Writes one setting. For bit registers, bits outside the item's writable
// mask keep their current value whatever [value] says.
DfWriteResult dfSettingsWrite(uint8_t id, int32_t value);

// Bumped after every successful write, so cached packets can be refreshed.
uint32_t dfSettingsGeneration();

// Any data flash parameter, by address. The firmware only accepts addresses
// listed in df_catalog.h (generated by tools/gen_df_catalog.py), within TI's
// min/max; addresses of the hand-picked settings go through dfSettingsWrite
// and keep their tighter limits.
DfWriteResult dfWriteAddress(uint16_t addr, int32_t value);

// Raw data flash bytes for the app to decode. Reading changes nothing, so any
// address in 0x4000-0x5FFF is allowed. At most DF_READ_MAX bytes.
#define DF_READ_MAX 480
bool dfReadRaw(uint16_t addr, uint16_t len, uint8_t *out);
