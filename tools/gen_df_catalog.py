"""Generate the data flash catalog for the firmware and the phone app.

    python tools/gen_df_catalog.py [path/to/hero_bms]

Input:  docs/df_table_4800_0_04.json -- TI SLUUBT5C Table 19-1, one entry per
        BQStudio Data Memory parameter (999 of them).
        docs/df_bits_4800_0_04.json  -- bit names and meanings of the hex
        registers, from the TRM's per-parameter sections (trm_parse_bits.py).
Output: main/df_catalog.h                 writable parameters, for the firmware
        <hero_bms>/lib/ble/df_catalog.dart every parameter, for the app

The firmware only accepts writes to addresses in df_catalog.h, within TI's
min/max. The 42 hand-picked settings in df_settings.cpp keep their tighter
LiFePO4 limits on top of that. Everything else here is TI's own range, which
is the full range of the type for most entries -- the app shows that warning.

READ_ONLY below is the policy: parameters where one wrong value can brick the
pack, cut SMBus communication, blow the fuse, or corrupt learned/calibration
data. They are shown in the app but only BQStudio can change them.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "hero_bms"

READ_ONLY_CLASSES = {
    "Calibration",   # needs reference measurements; wrong gains corrupt every reading
    "System Data",   # manufacturer blocks and DF integrity signatures
    "Ra Table",      # learned cell resistance tables
    "Black Box",     # fault logs
    "Lifetimes",     # lifetime logs
    "PF Status",     # captured at a permanent failure
}
READ_ONLY_SUBCLASSES = {
    ("Settings", "SMBus"),              # change the address and the ESP32 loses the gauge
    ("Settings", "Fuse"),               # can blow the pack fuse: irreversible
    ("Settings", "Permanent Failure"),  # enabling PF can latch the pack off
    ("Settings", "Manufacturing"),      # Mfg Status Init: FET_EN/GAUGE_EN after a reset
    ("Settings", "Current Scaling"),    # rescales every current and capacity
    ("Gas Gauging", "State"),           # learned QMax, cycle count, update status
}
READ_ONLY_NAMES = {
    "Cell Configuration",               # wiring: number of series cells
    "Pin Configuration",                # multi-function pin assignments
    "IO Config",
    "GPIO Sealed Access Config",
    *(f"FlagMapSetUp{i}" for i in range(8)),
}

SIZES = {"U1": 1, "I1": 1, "H1": 1, "U2": 2, "I2": 2, "H2": 2, "U4": 4, "I4": 4, "H4": 4, "F4": 4}
INT32_MAX = 2**31 - 1


def size_of(t):
    return SIZES.get(t) or int(t[1:]) + 1   # Sn: length byte + n chars


def number(s):
    s = s.strip()
    try:
        return int(s, 16) if s.lower().startswith("0x") else int(s)
    except ValueError:
        return None


def writable(p):
    if p["type"] not in SIZES or p["type"] == "F4":
        return False   # strings and TI floats
    if p["cls"] in READ_ONLY_CLASSES or (p["cls"], p["sub"]) in READ_ONLY_SUBCLASSES:
        return False
    if p["name"] in READ_ONLY_NAMES:
        return False
    return number(p["min"]) is not None and number(p["max"]) is not None


def main():
    doc = json.loads((ROOT / "docs/df_table_4800_0_04.json").read_text(encoding="utf-8"))
    params = doc["params"]
    bits = json.loads((ROOT / "docs/df_bits_4800_0_04.json").read_text(encoding="utf-8"))
    for p in params:
        p["addr_i"] = int(p["addr"], 16)
        if p["type"].startswith("S"):   # the parser split string defaults at a space
            p["default"], p["unit"] = (p["default"] + " " + p["unit"]).strip(), ""
        p["writable"] = writable(p)

    w = sorted((p for p in params if p["writable"]), key=lambda p: p["addr_i"])

    # ---- firmware ---------------------------------------------------------
    lines = [
        "// Generated by tools/gen_df_catalog.py from docs/df_table_4800_0_04.json.",
        "// Do not edit: change the generator's READ_ONLY policy and rerun it.",
        f"// {len(w)} writable of {len(params)} data flash parameters, sorted by address.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "enum class DfType : uint8_t { U1, I1, H1, U2, I2, H2, U4, I4, H4 };",
        "",
        "struct DfParam {",
        "    uint16_t addr;",
        "    DfType   type;",
        "    int32_t  min, max;",
        "};",
        "",
        "constexpr DfParam kDfWritable[] = {",
    ]
    for p in w:
        lo, hi = number(p["min"]), min(number(p["max"]), INT32_MAX)
        lines.append(f"    {{ 0x{p['addr_i']:04X}, DfType::{p['type']}, {lo}, {hi} }},"
                     f"  // {p['cls']} / {p['sub']} / {p['name']}")
    lines += ["};", ""]
    (ROOT / "main/df_catalog.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    # ---- app --------------------------------------------------------------
    def dart_str(s):
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"

    out = [
        "// Generated by tools/gen_df_catalog.py in the firmware repo, from TI SLUUBT5C",
        "// Table 19-1 (bq40z80 firmware 4800_0_04). Do not edit by hand.",
        "",
        "import 'df_param.dart';",
        "",
        "const dfClasses = [" + ", ".join(dart_str(c) for c in doc["classes"]) + "];",
        "",
        f"/// {len(params)} parameters, {len(w)} of them writable from the app.",
        "const dfParams = <DfParam>[",
    ]
    def dart_bits(addr):
        fields = bits.get(addr)
        if not fields:
            return ""
        items = []
        for b in fields:
            values = ", ".join(dart_str(v) for v in b["values"])
            items.append(f"DfBit({dart_str(b['name'])}, {b['lo']}, {b['width']}, "
                         f"{dart_str(b['desc'])}, [{values}])")
        return ", bits: [" + ", ".join(items) + "]"

    for p in params:
        lo, hi = number(p["min"]), number(p["max"])
        out.append(
            f"  DfParam({dart_str(p['cls'])}, {dart_str(p['sub'])}, 0x{p['addr_i']:04X}, "
            f"{dart_str(p['name'])}, {dart_str(p['type'])}, "
            f"{'null' if lo is None else lo}, {'null' if hi is None else hi}, "
            f"{dart_str(p['default'])}, {dart_str(p['unit'])}, {'true' if p['writable'] else 'false'}"
            f"{dart_bits(p['addr'])}),")
    out += ["];", ""]
    (APP / "lib/ble/df_catalog.dart").write_text("\n".join(out), encoding="utf-8", newline="\n")

    print(f"{len(params)} parameters, {len(w)} writable, {len(bits)} with bit definitions")


if __name__ == "__main__":
    main()
